const byRatingDesc = (a: ServiceDTO, b: ServiceDTO) => (b.rating ?? 0) - (a.rating ?? 0);
const bySpeedDesc = (a: ServiceDTO, b: ServiceDTO) =>
  (b.claimedSpeedMbps ?? 0) - (a.claimedSpeedMbps ?? 0);

const hasTag = (tags: string[]) => (s: ServiceDTO) => tags.some((t) => s.tags.includes(t));
const hasPlatform = (platform: string) => (s: ServiceDTO) => s.platforms.includes(platform);

